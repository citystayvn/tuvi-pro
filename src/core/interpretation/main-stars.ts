import { PALACE_ORDER, type PalaceName } from "./cycle-stars";
import type { AuxStarInterpretation } from "./aux-stars";

function full(lines: string[]): Record<PalaceName, string> {
  if (lines.length !== 12) throw new Error("Cần đúng 12 câu luận giải theo cung");
  return Object.fromEntries(PALACE_ORDER.map((n, i) => [n, lines[i]])) as Record<PalaceName, string>;
}

const CT = "Chính tinh";

function star(
  id: string,
  name: string,
  core: string,
  positive: string,
  negative: string,
  favorable: string,
  unfavorable: string | undefined,
  lines: string[],
  extra: Partial<AuxStarInterpretation> = {},
): AuxStarInterpretation {
  return { id, name, group: CT, core, positive, negative, favorable, unfavorable, palaces: full(lines), combos: [], ...extra };
}

