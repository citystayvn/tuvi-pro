export type PalaceName = (typeof PALACE_ORDER)[number];

export type ComboScope = "dong-cung" | "tam-phuong";

/** Tổ hợp có căn cứ truyền thống: chỉ hiện khi gặp ít nhất một sao trong `with`. */
export interface ComboRule {
  with: string[];
  scope: ComboScope;
  tone: "good" | "bad" | "mixed";
  text: string;
}

export interface CycleStarInterpretation {
  id: string;
  name: string;
  ring: "thai-tue" | "bac-si";
  core: string;
  positive: string;
  negative: string;
  palaces: Record<PalaceName, string>;
  combos: ComboRule[];
}

export const RING_LABEL = { "thai-tue": "Vòng Thái Tuế", "bac-si": "Vòng Bác Sĩ" } as const;

/** Câu luận theo thứ tự PALACE_ORDER. */
function p(lines: string[]): Record<PalaceName, string> {
  if (lines.length !== 12) throw new Error("Cần đúng 12 câu luận giải theo cung");
  return Object.fromEntries(PALACE_ORDER.map((name, i) => [name, lines[i]])) as Record<PalaceName, string>;
}

